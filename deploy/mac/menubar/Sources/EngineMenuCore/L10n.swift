public struct Localized {
    public let key: L10n
    public let args: [String]
    public let nested: [Localized]
    public init(_ key: L10n, _ args: String...) { self.key = key; self.args = args; self.nested = [] }
    public init(_ key: L10n, relative: Localized, prefix: [String] = []) { self.key = key; self.args = prefix; self.nested = [relative] }
    public var text: String { L10n.render(key, args + nested.map(\.text)) }
}
