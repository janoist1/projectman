import { readdirSync } from 'node:fs';
import { join } from 'node:path';

export const BARRELS = ['packages/shared/src', 'apps/server/src/contracts'] as const;

// Preserve the existing public API: these helpers are imported only by their owning modules.
const INTERNAL_SHARED_FILES = new Set([
  'config/operator-member.ts',
  'config/team-rule-ids.ts',
  'domain/feedback-origin.ts',
  'domain/palette.ts',
]);

export function generateBarrel(root: string, directory: (typeof BARRELS)[number]): string {
  function sources(folder: string, prefix = ''): string[] {
    return readdirSync(folder, { withFileTypes: true }).flatMap((entry) => {
      const path = `${prefix}${entry.name}`;
      if (entry.isDirectory()) {
        return entry.name === '__snapshots__' ? [] : sources(join(folder, entry.name), `${path}/`);
      }
      if (
        !entry.isFile() ||
        !entry.name.endsWith('.ts') ||
        /\.(?:test|spec|d)\.ts$/.test(entry.name) ||
        path === 'index.ts' ||
        (directory === 'packages/shared/src' && INTERNAL_SHARED_FILES.has(path))
      )
        return [];
      return [path.slice(0, -3)];
    });
  }
  return (
    '// Generated by npm run generate:barrels. Do not edit by hand.\n' +
    sources(join(root, directory))
      .sort()
      .map((path) => `export * from './${path}';\n`)
      .join('')
  );
}
